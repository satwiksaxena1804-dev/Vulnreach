"""Turn structured findings into prose, deterministically or with a model.

Guardrail: the verdict, confidence and evidence in the report are produced by
the static engine.  This module only produces *text*.  Any verdict-like field
returned by a model is ignored.
"""

from __future__ import annotations

import json
import os
import urllib.error
import urllib.request
from dataclasses import dataclass, field
from typing import Any

from ..errors import LLMError

SYSTEM_PROMPT = """You are a security analyst assistant explaining the output of a
static reachability analyzer. The analyzer's verdict, confidence, evidence paths
and rationale are authoritative and MUST NOT be changed, second-guessed or
re-labelled. If the evidence is insufficient, say so and describe what a human
should investigate. Return a JSON object with exactly these keys:
{"summary": string, "evidence": [string], "next_steps": [string]}.
Do not include a verdict or status field."""


@dataclass
class Explanation:
    """Narrative explanation attached to one finding."""

    finding_id: str
    verdict: str
    confidence: float
    summary: str
    evidence: list[str] = field(default_factory=list)
    next_steps: list[str] = field(default_factory=list)
    model: str | None = None
    ai_generated: bool = False
    notice: str | None = None

    def to_dict(self) -> dict[str, Any]:
        payload: dict[str, Any] = {
            "finding_id": self.finding_id,
            "verdict": self.verdict,
            "confidence": self.confidence,
            "summary": self.summary,
            "evidence": self.evidence,
            "next_steps": self.next_steps,
            "ai_generated": self.ai_generated,
            "model": self.model,
        }
        if self.notice:
            payload["notice"] = self.notice
        return payload

    def render(self) -> str:
        lines = [
            f"{self.verdict.upper()}  {self.finding_id}  (confidence {self.confidence:.2f})",
            "",
            self.summary,
        ]
        if self.evidence:
            lines.extend(["", "Evidence:"])
            lines.extend(f"- {item}" for item in self.evidence)
        if self.next_steps:
            lines.extend(["", "Next steps:"])
            lines.extend(f"- {item}" for item in self.next_steps)
        if self.notice:
            lines.extend(["", f"Note: {self.notice}"])
        if self.ai_generated and self.model:
            lines.extend(
                [
                    "",
                    f"Explanation generated by {self.model}. The verdict above was not "
                    "produced or modified by the model.",
                ]
            )
        return "\n".join(lines)


@dataclass
class LlmConfig:
    base_url: str
    model: str
    api_key: str
    timeout: float = 60.0

    @classmethod
    def from_env(cls) -> LlmConfig | None:
        base_url = os.environ.get("VULNREACH_LLM_BASE_URL", "").strip()
        model = os.environ.get("VULNREACH_LLM_MODEL", "").strip()
        api_key = os.environ.get("VULNREACH_LLM_API_KEY", "").strip()
        if not (base_url and model and api_key):
            return None
        return cls(base_url=base_url, model=model, api_key=api_key)


def explain_finding(finding: dict[str, Any], *, use_ai: bool = False) -> Explanation:
    """Explain one finding from a VulnReach JSON report."""
    explanation = template_explanation(finding)
    if not use_ai:
        return explanation

    config = LlmConfig.from_env()
    if config is None:
        explanation.notice = (
            "AI explanation requested but VULNREACH_LLM_BASE_URL, VULNREACH_LLM_MODEL and "
            "VULNREACH_LLM_API_KEY are not all set; showing the deterministic explanation."
        )
        return explanation

    try:
        generated = _call_model(finding, config)
    except LLMError as exc:
        explanation.notice = (
            f"AI explanation unavailable ({exc}); showing the deterministic explanation."
        )
        return explanation

    explanation.summary = generated["summary"]
    explanation.evidence = generated["evidence"] or explanation.evidence
    explanation.next_steps = generated["next_steps"] or explanation.next_steps
    explanation.ai_generated = True
    explanation.model = config.model
    return explanation


def template_explanation(finding: dict[str, Any]) -> Explanation:
    advisory = finding.get("advisory") or {}
    dependency = finding.get("dependency") or {}
    verdict = str(finding.get("verdict") or "unknown")
    confidence = float(finding.get("confidence") or 0.0)
    package = dependency.get("name") or "the dependency"
    version = dependency.get("version") or "an unknown version"

    summary = (
        f"{advisory.get('id', 'The advisory')} affects {package} {version}. "
        f"VulnReach concludes the vulnerable code is {verdict.replace('_', ' ')} "
        f"with confidence {confidence:.2f}."
    )

    evidence = [
        str(item.get("message"))
        for item in finding.get("rationale") or []
        if isinstance(item, dict) and item.get("message")
    ]
    for path in finding.get("paths") or []:
        hops = path.get("hops") or []
        if not hops:
            continue
        steps = [str(hops[0].get("from_label") or "")]
        for hop in hops:
            location = (hop.get("location") or {}).get("path")
            line = (hop.get("location") or {}).get("line")
            suffix = f" ({location}:{line})" if location else ""
            steps.append(f"{hop.get('to_label')}{suffix}")
        evidence.append(" -> ".join(step for step in steps if step))

    next_steps: list[str] = []
    if finding.get("remediation"):
        next_steps.append(str(finding["remediation"]))
    if verdict == "reachable":
        next_steps.append(
            "Confirm the affected path is exercised in production and remove the call or upgrade."
        )
    elif verdict == "uncertain":
        next_steps.append(
            "Inspect the cited uncertainty (missing symbols, version, or dynamic access) manually."
        )
    else:
        next_steps.append(
            "Verify the inferred entry points and any dynamic imports before "
            "relying on this result."
        )

    return Explanation(
        finding_id=str(finding.get("id") or "unknown"),
        verdict=verdict,
        confidence=confidence,
        summary=summary,
        evidence=evidence,
        next_steps=next_steps,
    )


def _call_model(finding: dict[str, Any], config: LlmConfig) -> dict[str, Any]:
    endpoint = config.base_url.rstrip("/")
    if not endpoint.endswith("/chat/completions"):
        endpoint = f"{endpoint}/chat/completions"

    payload = {
        "model": config.model,
        "temperature": 0.1,
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {
                "role": "user",
                "content": (
                    "Explain this finding for a developer. Do not restate or alter the "
                    "verdict other than quoting it.\n\n"
                    + json.dumps(_minimal_finding(finding), indent=2)
                ),
            },
        ],
    }
    body = json.dumps(payload).encode("utf-8")
    request = urllib.request.Request(
        endpoint,
        data=body,
        headers={
            "Content-Type": "application/json",
            "Authorization": f"Bearer {config.api_key}",
            "User-Agent": "vulnreach/0.1.0",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=config.timeout) as response:
            data = json.loads(response.read().decode("utf-8"))
    except (urllib.error.HTTPError, urllib.error.URLError, TimeoutError, OSError) as exc:
        raise LLMError(str(exc)) from exc
    except (json.JSONDecodeError, UnicodeDecodeError) as exc:
        raise LLMError(f"invalid response from model endpoint: {exc}") from exc

    try:
        content = data["choices"][0]["message"]["content"]
    except (KeyError, IndexError, TypeError) as exc:
        raise LLMError("model response did not contain choices[0].message.content") from exc

    parsed = _parse_json_object(str(content))
    summary = parsed.get("summary")
    evidence = parsed.get("evidence")
    next_steps = parsed.get("next_steps")
    if not isinstance(summary, str) or not summary.strip():
        raise LLMError("model response did not contain a summary")
    return {
        "summary": summary.strip(),
        "evidence": [str(item) for item in evidence] if isinstance(evidence, list) else [],
        "next_steps": [str(item) for item in next_steps] if isinstance(next_steps, list) else [],
    }


def _parse_json_object(text: str) -> dict[str, Any]:
    cleaned = text.strip()
    if cleaned.startswith("```"):
        cleaned = cleaned.strip("`")
        if cleaned.startswith("json"):
            cleaned = cleaned[4:]
    try:
        parsed = json.loads(cleaned)
    except json.JSONDecodeError as exc:
        raise LLMError(f"model did not return JSON: {exc}") from exc
    if not isinstance(parsed, dict):
        raise LLMError("model returned JSON that is not an object")
    return parsed


def _minimal_finding(finding: dict[str, Any]) -> dict[str, Any]:
    """Strip fields the model does not need (and must not act on)."""
    return {
        "id": finding.get("id"),
        "verdict": finding.get("verdict"),
        "confidence": finding.get("confidence"),
        "advisory": {
            "id": (finding.get("advisory") or {}).get("id"),
            "summary": (finding.get("advisory") or {}).get("summary"),
            "severity": (finding.get("advisory") or {}).get("severity"),
            "fixed_versions": (finding.get("advisory") or {}).get("fixed_versions"),
        },
        "dependency": finding.get("dependency"),
        "vulnerable_symbols": finding.get("vulnerable_symbols"),
        "rationale": finding.get("rationale"),
        "paths": finding.get("paths"),
        "uncertainty": finding.get("uncertainty"),
        "remediation": finding.get("remediation"),
    }
