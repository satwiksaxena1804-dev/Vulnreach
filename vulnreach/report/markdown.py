"""Human-readable Markdown reports for pull requests and documentation."""

from __future__ import annotations

from ..model import Finding
from ..reachability import AnalysisResult, remediation_hint


def render_markdown(result: AnalysisResult) -> str:
    """Render the analysis result as Markdown."""
    summary = result.summary
    lines: list[str] = [
        "# VulnReach report",
        "",
        f"**Project:** `{result.project.name}`"
        + (f" `{result.project.version}`" if result.project.version else ""),
        f"**Root:** `{result.project.root}`",
        f"**Advisory source:** {result.advisory_source}",
        f"**Modules:** {result.metrics.modules_scanned} scanned, "
        f"{result.metrics.modules_failed} failed  ·  "
        f"**Calls:** {result.metrics.resolved_calls}/{result.metrics.total_calls} resolved "
        f"({result.metrics.resolution_coverage:.0%})",
        "",
        "## Summary",
        "",
        "| Verdict | Count |",
        "| --- | ---: |",
        f"| Reachable | {summary['reachable']} |",
        f"| Uncertain | {summary['uncertain']} |",
        f"| Not reachable | {summary['not_reachable']} |",
        f"| Excluded (version not affected) | {summary['advisories_excluded']} |",
        "",
    ]

    if result.findings:
        lines.extend(["## Findings", ""])
        for index, finding in enumerate(result.findings, start=1):
            lines.extend(_finding_lines(index, finding))
    else:
        lines.extend(
            [
                "## Findings",
                "",
                "No advisory findings were produced for the analysed dependencies.",
                "",
            ]
        )

    if result.dependencies:
        lines.extend(
            [
                "## Dependencies",
                "",
                "| Package | Version | Direct | Source |",
                "| --- | --- | --- | --- |",
            ]
        )
        for dependency in result.dependencies:
            lines.append(
                f"| `{dependency.name}` | {dependency.version or 'unknown'} | "
                f"{'yes' if dependency.direct else 'no'} | {dependency.source} |"
            )
        lines.append("")

    if result.limitations:
        lines.extend(["## Limitations", ""])
        lines.extend(f"- {limitation}" for limitation in result.limitations)
        lines.append("")

    if result.warnings:
        lines.extend(["## Warnings", ""])
        lines.extend(f"- {warning}" for warning in sorted(set(result.warnings)))
        lines.append("")

    lines.extend(
        [
            "---",
            "",
            "Generated by VulnReach. Verdicts come from static call-graph analysis; "
            "no language model participates in the decision.",
            "",
        ]
    )
    return "\n".join(lines)


def _finding_lines(index: int, finding: Finding) -> list[str]:
    advisory = finding.advisory
    verdict = finding.verdict.value.replace("_", " ").upper()
    lines = [
        f"### {index}. {verdict} — `{advisory.id}`",
        "",
        f"**Package:** `{finding.dependency.name}` "
        f"{finding.dependency.version or '(unknown version)'}  ",
        f"**Severity:** {advisory.severity}  ",
        f"**Confidence:** {finding.confidence:.2f}  ",
        f"**Affected status:** {finding.affected_status}",
        "",
        advisory.summary or "No summary provided by the advisory.",
        "",
    ]

    if finding.vulnerable_symbols:
        symbols = ", ".join(f"`{symbol}`" for symbol in finding.vulnerable_symbols)
        lines.extend([f"**Vulnerable symbols:** {symbols}", ""])

    if finding.paths:
        lines.extend(["**Evidence path:**", ""])
        for path_index, path in enumerate(finding.paths, start=1):
            label = "confirmed" if path.is_confirmed else "reference only"
            lines.append(f"{path_index}. Path ({label}, {path.length} hop(s)):")
            for node_index, (_node_id, node_label) in enumerate(path.nodes):
                location = ""
                if node_index > 0:
                    hop = path.hops[node_index - 1]
                    if hop.location is not None:
                        location = f" — `{hop.location}`"
                marker = "   " if node_index else "-"
                lines.append(f"   {marker} `{node_label}`{location}")
            lines.append("")
    else:
        lines.extend(["**Evidence path:** none found.", ""])

    lines.extend(["**Why this verdict:**", ""])
    lines.extend(f"- `{rationale.code}`: {rationale.message}" for rationale in finding.rationale)
    lines.append("")

    if finding.uncertainty:
        lines.extend(["**Uncertainty considered:**", ""])
        for gap in finding.uncertainty:
            lines.append(f"- `{gap.kind.value}` at `{gap.location}`: {gap.detail}")
        lines.append("")

    hint = remediation_hint(finding)
    if hint:
        lines.extend([f"**Remediation:** {hint}", ""])

    return lines
